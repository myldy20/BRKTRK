const assert = require("node:assert/strict");
const policy = require("./audio-lifecycle-policy.js");

let state = policy.initialState();
assert.equal(state.status, "disabled");
state = policy.transition(state, { type: "INIT_REQUEST" });
assert.equal(state.status, "initializing");
assert.equal(state.initGeneration, 1);
state = policy.transition(state, { type: "INIT_READY", contextState: "running" });
assert.equal(state.status, "ready");
assert.equal(state.requiresGesture, false);
state = policy.transition(state, { type: "CONTEXT_STATE", contextState: "suspended" });
assert.equal(state.status, "suspended");
assert.equal(state.requiresGesture, true);
state = policy.transition(state, { type: "RESUME_REQUEST" });
assert.equal(state.status, "resuming");
state = policy.transition(state, { type: "CONTEXT_STATE", contextState: "running" });
assert.equal(state.status, "ready");
assert.equal(state.requiresGesture, false);
state = policy.transition(state, { type: "VISIBILITY_HIDDEN" });
assert.equal(state.visibility, "hidden");
state = policy.transition(state, { type: "PAGE_HIDE" });
assert.equal(state.pageHidden, true);
state = policy.transition(state, { type: "PAGE_SHOW", persisted: true });
assert.equal(state.pageHidden, false);
assert.equal(state.persistedRestore, true);
state = policy.transition(state, { type: "RESUME_FAILED", error: "blocked" });
assert.equal(state.status, "error");
assert.equal(state.error, "blocked");
assert.equal(state.requiresGesture, true);
console.log("BRKTRK audio lifecycle policy tests passed");
